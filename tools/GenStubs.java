import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Type;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ParameterMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.Statement;
import java.util.Arrays;
import java.util.Comparator;
import java.util.stream.Collectors;

/**
 * Generates the JDBC adapter base classes. Run with:
 *   java tools/GenStubs.java turso-jdbc/src/main/java/io/turso/jdbc/base
 */
public final class GenStubs {
  private static final String PKG = "io.turso.jdbc.base";

  public static void main(String[] args) throws Exception {
    Path out = Path.of(args[0]);
    Files.createDirectories(out);
    gen(out, Connection.class, "AbstractConnection", null);
    gen(out, Statement.class, "AbstractStatement", null);
    gen(out, PreparedStatement.class, "AbstractPreparedStatement", "AbstractStatement");
    gen(out, ResultSet.class, "AbstractResultSet", null);
    gen(out, ResultSetMetaData.class, "AbstractResultSetMetaData", null);
    gen(out, ParameterMetaData.class, "AbstractParameterMetaData", null);
    gen(out, DatabaseMetaData.class, "AbstractDatabaseMetaData", null);
    genSupport(out.getParent(), "TursoPreparedSupport", "io.turso.jdbc.TursoStatement");
  }

  /**
   * Generates a class extending TursoStatement and implementing PreparedStatement, so the
   * prepared statement inherits the statement implementation and only adds the missing methods.
   */
  private static void genSupport(Path out, String name, String superClass) throws Exception {
    StringBuilder sb = new StringBuilder();
    sb.append("package io.turso.jdbc;\n\n");
    sb.append("/** Generated by tools/GenStubs.java. Do not edit. */\n");
    sb.append("@SuppressWarnings(\"all\")\n");
    sb.append("public abstract class ").append(name).append(" extends ").append(superClass)
        .append(" implements java.sql.PreparedStatement {\n");
    sb.append("  protected ").append(name)
        .append("(io.turso.jdbc.TursoConnection connection) { super(connection); }\n\n");
    Method[] methods = PreparedStatement.class.getDeclaredMethods();
    Arrays.sort(methods, Comparator.comparing(Method::getName).thenComparing(Method::toString));
    for (Method m : methods) {
      if (m.isSynthetic() || Modifier.isStatic(m.getModifiers()) || m.isDefault()) {
        continue;
      }
      sb.append("  @Override\n  public ");
      if (m.getTypeParameters().length > 0) {
        sb.append(typeParams(m)).append(" ");
      }
      sb.append(m.getGenericReturnType().getTypeName()).append(" ").append(m.getName()).append("(");
      Type[] pts = m.getGenericParameterTypes();
      for (int i = 0; i < pts.length; i++) {
        if (i > 0) {
          sb.append(", ");
        }
        Type t = pts[i];
        if (m.isVarArgs() && i == pts.length - 1) {
          Type comp = ((GenericArrayType) t).getGenericComponentType();
          sb.append(comp.getTypeName()).append("... a").append(i);
        } else {
          sb.append(t.getTypeName()).append(" a").append(i);
        }
      }
      sb.append(")");
      if (m.getExceptionTypes().length > 0) {
        sb.append(" throws ").append(Arrays.stream(m.getExceptionTypes())
            .map(Class::getName).collect(Collectors.joining(", ")));
      }
      sb.append(" {\n");
      boolean declaresSqlException = Arrays.stream(m.getExceptionTypes())
          .anyMatch(e -> e.isAssignableFrom(java.sql.SQLException.class));
      if (declaresSqlException) {
        sb.append("    throw new java.sql.SQLFeatureNotSupportedException(\"").append(m.getName()).append("\");\n");
      } else {
        sb.append("    throw new UnsupportedOperationException(\"").append(m.getName()).append("\");\n");
      }
      sb.append("  }\n");
    }
    sb.append("}\n");
    Files.writeString(out.resolve(name + ".java"), sb.toString());
  }

  private static void gen(Path out, Class<?> iface, String name, String superClass) throws Exception {
    StringBuilder sb = new StringBuilder();
    sb.append("package ").append(PKG).append(";\n\n");
    sb.append("/** Generated by tools/GenStubs.java. Do not edit. */\n");
    sb.append("@SuppressWarnings(\"all\")\n");
    sb.append("public abstract class ").append(name).append(" ");
    if (superClass != null) {
      sb.append("extends ").append(superClass).append(" ");
    }
    sb.append("implements ").append(iface.getName()).append(" {\n");

    Method[] methods = iface.getMethods();
    Arrays.sort(methods, Comparator.comparing(Method::getName).thenComparing(Method::toString));
    for (Method m : methods) {
      if (m.isSynthetic() || Modifier.isStatic(m.getModifiers()) || m.isDefault()) {
        continue;
      }
      sb.append("  @Override\n  public ");
      if (m.getTypeParameters().length > 0) {
        sb.append(typeParams(m)).append(" ");
      }
      sb.append(m.getGenericReturnType().getTypeName()).append(" ").append(m.getName()).append("(");
      Type[] pts = m.getGenericParameterTypes();
      for (int i = 0; i < pts.length; i++) {
        if (i > 0) {
          sb.append(", ");
        }
        Type t = pts[i];
        if (m.isVarArgs() && i == pts.length - 1) {
          Type comp = ((GenericArrayType) t).getGenericComponentType();
          sb.append(comp.getTypeName()).append("... a").append(i);
        } else {
          sb.append(t.getTypeName()).append(" a").append(i);
        }
      }
      sb.append(")");
      if (m.getExceptionTypes().length > 0) {
        sb.append(" throws ").append(Arrays.stream(m.getExceptionTypes())
            .map(Class::getName).collect(Collectors.joining(", ")));
      }
      sb.append(" {\n");
      boolean declaresSqlException = Arrays.stream(m.getExceptionTypes())
          .anyMatch(e -> e.isAssignableFrom(java.sql.SQLException.class));
      if (declaresSqlException) {
        sb.append("    throw new java.sql.SQLFeatureNotSupportedException(\"").append(m.getName()).append("\");\n");
      } else {
        sb.append("    throw new UnsupportedOperationException(\"").append(m.getName()).append("\");\n");
      }
      sb.append("  }\n");
    }
    sb.append("}\n");
    Files.writeString(out.resolve(name + ".java"), sb.toString());
  }

  private static String typeParams(Method m) {
    return "<" + Arrays.stream(m.getTypeParameters()).map(tp -> {
      Type[] bounds = tp.getBounds();
      if (bounds.length == 1 && bounds[0] == Object.class) {
        return tp.getName();
      }
      return tp.getName() + " extends " + Arrays.stream(bounds)
          .map(Type::getTypeName).collect(Collectors.joining(" & "));
    }).collect(Collectors.joining(", ")) + ">";
  }
}
